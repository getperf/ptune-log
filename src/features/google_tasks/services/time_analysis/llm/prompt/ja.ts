import { TimeAnalysisPromptParams } from '.';

/**
 * 日本語版：時間分析プロンプト
 *
 * 目的（既存維持）:
 * - 事実ベースでのタスク実行整理
 *
 * 補足（最小追加）:
 * - タスクタイトル由来のトピック化を明示
 * - reviewFlags は存在表現を禁止し、意味変換のみ許可
 */
export function buildTimeAnalysisPromptJa(
  params: TimeAnalysisPromptParams,
): string {
  const { yamlText, header } = params;

  return `
以下は、1日分のタスク実行データを YAML 形式で表したものです。

${header ?? ''}

${yamlText}

---

## 役割
あなたは「事実ベースでタスク実行を整理・要約するアシスタント」です。
推測や一般論は行わず、与えられたデータから直接読み取れる内容のみを整理してください。

---

## 基本ルール（必須）
- **推測・一般論は禁止**（「〜が多い」「〜の傾向が見られた」などは禁止）
- **原因の断定は禁止**（可能性に触れる場合も1行・タスク単位まで）
- **🚫 が付いた日常タスクはすべて分析対象外**
- 出力は **短い箇条書き** を基本とする（1タスク=1行）

---

## 数値ルール（必須）
- planned / actual / delta はすべて **ポモドーロ数**
- delta = actual - planned
- 解釈:
  - delta > 0 : 計画超過（遅れ）
  - delta < 0 : 計画未満（前倒し）

---

## トピック化（補足・必須）
- 各タスクは **最初にトピックを付与**して整理する
- トピックは **タスクタイトルから要約した短い名詞句**
  - 例:
    - 「タスクの質の分析enum廃止__ptune-log」
      → 「タスク分析機能のリファクタリング」
- 抽象語のみ（例:「作業」「雑務」）は使用しない
- 類似内容のタスクは **同一トピック名** にまとめる

---

## reviewFlags の扱い（補足・必須）
- 「reviewFlags が存在する」という表現は禁止
- reviewFlags は **問題内容の説明文** に変換して記載する

変換例（名称は出さない）:
- toolOrEnvIssue:
  - ツール・環境・設定に起因する阻害
- stuckUnknown:
  - 原因が特定できない停滞
- scopeUnclear:
  - 完了条件・範囲が不明確
- decisionPending: 
  - 判断が保留のまま作業が進行・完了した
- unresolved: 
  - 完了扱いだが未解決の事項が残っている
- newIssueFound: 
  - 作業中に新たな問題が発見された

※ 複数ある場合は簡潔にまとめてよい

---

## 「完了タスクに残った問題・宿題」の扱い
以下の **データ上の根拠がある場合のみ** 記載する:
- notes に TODO / pending / 未対応 が明示されている
- reviewFlags から阻害・停滞が読み取れる
- 完了扱いだが未対応事項がテキスト上に残っている

根拠がない場合は記載しない

---

## 出力構成（既存維持）
### 1. トピック別の進捗
- トピック名:
  - タスク名（planned / actual / delta の要点）

### 2. 遅れが発生したタスク（delta > 0）
- トピック / タスク名: 遅れ内容（数値）

### 3. 前倒しで進んだタスク（delta < 0）
- トピック / タスク名: 前倒し内容（数値）

### 4. 問題・阻害が確認されたタスク
- トピック / タスク名: 問題内容（reviewFlags の意味変換）

### 5. 宿題・未解決事項
- トピック / タスク名: 残件内容（根拠を簡潔に）

---

## 日次要約（補足）
- 抽象的な総評は禁止
- **当日の主要トピックのみを列挙**
- 各行は「どのトピックで、進捗／遅れがあったか」という **事実のみ**

（最大 3〜5 行）

---

## 禁止表現（重要）
- 「〜が多い」「〜の傾向が見られた」
- 「全体として」「総じて」
- 「reviewFlags が存在する」
- データにない原因・背景の説明
`;
}
